def make_encrypted():
    """비밀번호(1234)가 걸린 스마트스토어 샘플. msoffcrypto-tool 필요."""
    try:
        from msoffcrypto.format.ooxml import OOXMLFile
    except Exception as e:  # pragma: no cover
        print("msoffcrypto-tool 이 없어 암호 샘플은 건너뜀:", e)
        return
    with open(OUT / "스마트스토어_주문샘플.xlsx", "rb") as src, \
            open(OUT / "스마트스토어_암호걸린샘플_비번1234.xlsx", "wb") as dst:
        OOXMLFile(src).encrypt("1234", dst)


